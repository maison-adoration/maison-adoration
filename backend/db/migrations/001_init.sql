-- Schéma initial PostgreSQL — Maison d'Adoration pour les Nations
-- Les anciens identifiants MongoDB (ObjectId, 24 caractères hexadécimaux)
-- sont conservés comme `id` lors de la migration : les liens existants restent valides.

CREATE TYPE user_role        AS ENUM ('user', 'admin', 'super-admin');
CREATE TYPE content_type     AS ENUM ('activity', 'podcast', 'video', 'pdf');
CREATE TYPE enrollment_source AS ENUM ('purchase', 'manual', 'migration');
CREATE TYPE payment_status   AS ENUM ('pending', 'success', 'failed');

-- Identifiant texte aléatoire pour les nouvelles lignes (même format que MongoDB).
CREATE FUNCTION gen_object_id() RETURNS text
  LANGUAGE sql VOLATILE AS
$$ SELECT lpad(to_hex(floor(extract(epoch FROM clock_timestamp()))::bigint), 8, '0')
          || substr(md5(random()::text || clock_timestamp()::text), 1, 16) $$;

CREATE FUNCTION set_updated_at() RETURNS trigger
  LANGUAGE plpgsql AS
$$ BEGIN NEW.updated_at := now(); RETURN NEW; END $$;

CREATE TABLE users (
  id            text PRIMARY KEY DEFAULT gen_object_id(),
  number        integer GENERATED BY DEFAULT AS IDENTITY UNIQUE, -- ancien userN (références de paiement)
  email         text NOT NULL,
  password_hash text NOT NULL,
  name          text NOT NULL,
  tel           text,
  country       text,
  role          user_role NOT NULL DEFAULT 'user',
  is_verified   boolean NOT NULL DEFAULT false,
  email_opt_in  boolean NOT NULL DEFAULT true,
  sms_opt_in    boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_email_lowercase CHECK (email = lower(email))
);
CREATE UNIQUE INDEX users_email_key ON users (email);
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE contents (
  id            text PRIMARY KEY DEFAULT gen_object_id(),
  number        integer GENERATED BY DEFAULT AS IDENTITY UNIQUE, -- ancien webinarN
  type          content_type NOT NULL,
  title         text NOT NULL,
  description   text NOT NULL DEFAULT '',
  price         numeric(10, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  url           text,          -- lien YouTube ou PDF : jamais renvoyé sans droit d'accès
  poster_url    text NOT NULL,
  created_by_id text REFERENCES users (id) ON DELETE SET NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX contents_type_created_idx ON contents (type, created_at DESC);
CREATE TRIGGER contents_updated_at BEFORE UPDATE ON contents
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE payments (
  id           text PRIMARY KEY DEFAULT gen_object_id(),
  user_id      text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  content_id   text NOT NULL REFERENCES contents (id) ON DELETE CASCADE,
  amount       numeric(10, 2) NOT NULL CHECK (amount > 0),
  currency     text NOT NULL,
  phone        text NOT NULL,
  provider     text NOT NULL DEFAULT 'flexpay',
  reference    text NOT NULL UNIQUE,   -- envoyée au prestataire, unique par tentative
  order_number text UNIQUE,            -- renvoyé par FlexPay
  status       payment_status NOT NULL DEFAULT 'pending',
  message      text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX payments_user_status_idx ON payments (user_id, status);
CREATE TRIGGER payments_updated_at BEFORE UPDATE ON payments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Droit d'accès d'un utilisateur à un contenu (remplace l'ancien tableau `conferences`).
CREATE TABLE enrollments (
  user_id    text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  content_id text NOT NULL REFERENCES contents (id) ON DELETE CASCADE,
  source     enrollment_source NOT NULL,
  payment_id text UNIQUE REFERENCES payments (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, content_id)
);
CREATE INDEX enrollments_content_idx ON enrollments (content_id);

CREATE TABLE push_subscriptions (
  id         text PRIMARY KEY DEFAULT gen_object_id(),
  endpoint   text NOT NULL UNIQUE,
  keys       jsonb NOT NULL,
  user_id    text REFERENCES users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);
